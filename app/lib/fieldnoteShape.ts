/** What the ledger knew about a work day when the note was written. Generated by code from commits; no model involved. */
export type DayContext = { day: string; commits: number; withClaude: number; files: number; where: string[]; firstAt?: string; lastAt?: string };

export type Fetched = {
  at: string;
  /** "ok" has text; "blocked" means the site answered but gave nothing readable; "failed" means it could not be reached. */
  status: "ok" | "blocked" | "failed";
  /** Where the link ended up after redirects (short links hide the real address). */
  finalUrl?: string;
  title?: string;
  author?: string;
  site?: string;
  /** The page's own text as it was when fetched: the snapshot, should the post later change or vanish. */
  text?: string;
  publishedAt?: string;
};
/** A model's label for what the link is, made only from the fetched page and share text, never from the person's words. */
export type Labelled = { at: string; model: string; what: string; kind: (typeof TRIGGER_KINDS)[number]; who?: string };

export type Capture = {
  /** Exactly what was pasted. */
  pasted: string;
  url: string | null;
  platform: Platform | null;
  shared: Shared;
  postedAt: string | null;
  /** How `postedAt` is known: decoded from the post's id, or stated by the page. */
  postedFrom?: "id" | "page";
  fetched?: Fetched;
  label?: Labelled;
};

export type FieldNote = {
  id: string;
  kind: Kind;
  /** When it was saved (server clock). Never changes. */
  at: string;
  /** The work day (05:00 to 05:00 London) it was saved in. */
  day: string;
  /** The work day it is about, when that is an earlier one: a note written afterwards, marked so it is not read as in-the-moment. */
  about?: string;
  late?: true;
  /** The person's own words, exactly as typed. */
  raw: string;
  satisfaction?: number;
  intensity?: number;
  mine?: Mine;
  feelings?: string[];
  via?: string;
  answers?: Record<string, string>;
  context?: DayContext;
  capture?: Capture;
  /** A reflection's period. */
  from?: string;
  to?: string;
  /** Later additions by the person. The original is never edited; second thoughts go here, dated. */
  addenda?: { at: string; text: string }[];
  /** Set aside by the person. Kept in storage, left out of exports unless asked for. */
  withdrawn?: string;
};

export type Gap = { day: string; commits: number; withClaude: number; where: string[] };
export type FieldView = {
  today: string;
  /** Today's facts from the ledger, for the owner. */
  context: DayContext | null;
  /** Recent work days that have work in the ledger and no micro or session record. */
  gaps: Gap[];
  counts: Record<Kind, number>;
  notes: FieldNote[];
};
